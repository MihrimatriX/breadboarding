/** 4096 baytlık karakter ROM'u. */
export const FONT_8X16: Uint8Array = (() => {
  const out = new Uint8Array(256 * 16);
  HEX.forEach((h, c) => {
    for (let r = 0; r < 16; r++) out[c * 16 + r] = parseInt(h.slice(r * 2, r * 2 + 2), 16);
  });
  return out;
})();

const REVERSE = new Map<number, number>(CODEPAGE.map((u, c) => [u, c] as [number, number]).filter(([u]) => u !== 0));

/** Karakter kodunu ekrana basılabilir metne çevirir (kontrol kodları boşluk olur). */
export function charToText(code: number): string {
  const u = CODEPAGE[code & 0xff];
  return u === 0 || u === 0xa0 || u === 0xad ? " " : String.fromCodePoint(u);
}

/** Unicode karakteri kod sayfasındaki koduna çevirir; yoksa undefined. */
export function textToChar(ch: string): number | undefined {
  return REVERSE.get(ch.codePointAt(0) ?? 0);
}
